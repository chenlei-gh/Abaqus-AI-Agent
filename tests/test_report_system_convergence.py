"""Comprehensive Test Matrix for Phase P2 Report System Convergence & Single Delivery Pipeline.

Validates the Iron Rules of Architectural Convergence:
1. Zero Stale Report Leakage:
   If official delivery pipeline fails or is blocked (DELIVERY_BLOCKED),
   report_markdown and report_html must be None (zero stale leakage),
   and task status must be FAILED.
2. ResultIntelligence Auxiliary Figures Do Not Block Official Delivery:
   Legitimate analytical charts (hotspots SVG, history curves) generated by
   ResultIntelligence do not trigger PermissionError or block official CAE delivery.
3. Unadmitted Foreign Figures Strictly Blocked:
   External or forged figures not declared in VisualizationSpecs or failing cryptographic
   admittance are strictly blocked in official delivery mode.
4. Non-deliverable Draft Diagnostic Contract:
   Non-production or uncompleted tasks produce reports explicitly marked with
   [DIAGNOSTIC / NON-DELIVERABLE DRAFT], with zero delivery card issued.
5. Single-Source Data Consistency for Markdown and HTML:
   Both Markdown and HTML are rendered from the same underlying EngineeringReportData,
   ensuring strict numeric and acceptance verdict consistency.
"""


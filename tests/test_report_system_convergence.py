class MockExecutor(AbaqusExecutor):
    """Mock executor for test coverage."""
    def __init__(self):
        self.executed_commands = []
        self._is_mock = True

    def execute(self, code, timeout=120):
        self.executed_commands.append(code)
        if "mdb.jobs[" in code and "status" in code:
            return "COMPLETED"
        return {"status": "completed"}

    def inspect_odb(self, path):
        return {"status": "available", "steps": ["Step-1"]}


def _create_mock_authentic_figure(
    tmp_path: Path,
    filename: str,
    spec: VisualizationSpec,
    run_id: str,
    input_hash: str,
    odb_sha256: str,
    output_position: str = "INTEGRATION_POINT",
) -> ReportFigure:
    """Helper to construct a cryptographically signed mock CAE visualization figure."""
    img_file = tmp_path / filename
    img_bytes = b"<svg><rect width='100' height='100'/></svg>"
    img_file.write_bytes(img_bytes)
    img_sha = hashlib.sha256(img_bytes).hexdigest()

    nonce = "0123456789abcdef0123456789abcdef"
    token = compute_viewer_session_token(
        session_nonce=nonce,
        run_id=run_id,
        odb_sha256=odb_sha256,
        target_filename=img_file.name,
        image_sha256=img_sha,
    )
    ev = create_render_execution_evidence(
        session_nonce=nonce,
        run_id=run_id,
        odb_sha256=odb_sha256,
        input_hash=input_hash,
        rendered_figures=[{"filename": img_file.name, "image_sha256": img_sha}],
    )

    fig = spec.to_report_figure(str(img_file.as_posix()))
    fig.metadata["image_sha256"] = img_sha
    fig.metadata["sha256"] = img_sha
    fig.metadata["run_id"] = run_id
    fig.metadata["input_hash"] = input_hash
    fig.metadata["odb_sha256"] = odb_sha256
    fig.metadata["field"] = spec.field_name
    fig.metadata["component"] = spec.component
    fig.metadata["step"] = spec.step_name
    fig.metadata["frame"] = spec.frame_index
    fig.metadata["region"] = "WHOLE_MODEL"
    fig.metadata["output_position"] = output_position
    fig.metadata["viewer_rendered"] = True
    fig.metadata["session_nonce"] = nonce
    fig.metadata["viewer_session_token"] = token
    fig.metadata["render_execution_evidence"] = ev.to_dict()
    return fig



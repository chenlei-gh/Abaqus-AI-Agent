def test_single_source_data_consistency_markdown_and_html():
    """P1-2 Verification: Markdown and HTML render from the exact same EngineeringReportData instance."""
    builder = AdaptiveReportBuilder(
        physics_domain="structural",
        objective=AnalysisObjective.STATIC_STRENGTH,
    )

    criterion = CriterionResult(
        name="MaxMisesStress",
        passed=True,
        actual=314.92,
        operator="<=",
        limit=355.0,
        unit="MPa",
    )
    acceptance = AcceptanceResult(
        passed=True,
        criteria=(criterion,),
        status="PASS",
        result_validity="VALID",
        deliverable=True,
    )

    report_data = builder.build_report_data(
        title="Flange Assembly Stress Verification Report",
        case_id="case_flange_01",
        run_id="RUN-SINGLE-SOURCE",
        model_info={"name": "FlangeJoint", "max_mises_mpa": 314.92, "max_displacement_mm": 0.000777},
        results_info=(criterion,),
        acceptance_info=acceptance,
    )

    md_out = render_markdown(report_data)
    html_out = render_html(report_data)

    # 1. Identical title
    assert "# Flange Assembly Stress Verification Report" in md_out
    assert "<title>Flange Assembly Stress Verification Report</title>" in html_out

    # 2. Identical metrics
    assert "314.92" in md_out
    assert "314.92" in html_out
    assert "0.000777" in md_out
    assert "0.000777" in html_out

    # 3. Identical acceptance verdict
    assert "PASS" in md_out
    assert "PASS" in html_out


def test_result_intelligence_auxiliary_figures_do_not_block_official_delivery(tmp_path: Path):
    """P0-2: Verify that when ResultIntelligence generates auxiliary SVG charts (hotspots/curves),
    and verified CAE contour figures are provided, official delivery completes successfully
    without PermissionError or blocked delivery.
    """
    pipeline = DeterministicReportPipeline(
        builder=AdaptiveReportBuilder(
            physics_domain="structural",
            objective=AnalysisObjective.STATIC_STRENGTH,
        )
    )

    mock_odb = tmp_path / "valid.odb"
    mock_odb.write_bytes(b"\x7fSIMULIA_ODB_BINARY_HEADER" + b"\x00" * 1024)
    odb_sha = hashlib.sha256(mock_odb.read_bytes()).hexdigest()


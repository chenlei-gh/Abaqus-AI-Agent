def test_zero_stale_report_leakage_when_delivery_blocked(tmp_path: Path, monkeypatch):
    """P0-3 Verification: When official delivery is blocked, zero stale report strings are returned."""
    agent = AbaqusAIAgent(executor=MockExecutor(), mode="production")

    # Mock an analysis run that passes solver acceptance
    mock_odb = tmp_path / "mock.odb"
    mock_odb.write_bytes(b"\x7fSIMULIA_ODB_BINARY_HEADER" + b"\x00" * 1024)

    mock_run = MagicMock(spec=AnalysisRun)
    mock_run.id = "run-test-blocked-001"
    mock_run.model_name = "Model_Cantilever"
    mock_run.job_name = "Job_Cantilever"
    mock_run.work_dir = str(tmp_path)
    mock_run.state = AnalysisRunState.ACCEPTED
    mock_run.engineering_status = "RESULT_VALID"
    mock_run.acceptance_passed = True
    mock_run.odb_path = str(mock_odb)
    mock_run.metrics = (
        EngineeringMetric(name="max_mises", value=528.9, unit="MPa"),
        EngineeringMetric(name="max_displacement", value=0.00237, unit="mm"),
    )
    mock_run.acceptance = AcceptanceResult(
        passed=True,
        criteria=(),
        status="PASS",
        result_validity="VALID",
        deliverable=True,
    )
    monkeypatch.setattr(agent, "analysis_run", lambda *args, **kwargs: mock_run)

    # In production mode with require_production=True, live Viewer is not present,
    # so DeterministicReportPipeline will raise FileNotFoundError / PermissionError.
    # This must strictly set:
    # - task_status = FAILED
    # - engineering_status = DELIVERY_BLOCKED
    # - report_markdown is None
    # - report_html is None
    # - delivery_card is None
    from abaqus_ai_agent.paths import create_external_project_context

    project = create_external_project_context(tmp_path / "customer", enforce_outside_repo=False)
    task_res = agent.solve_requirement(
        _build_test_intent(),
        require_production=True,
        workdir=str(project.solver_dir),
        project_context=project,
    )

    assert task_res.status == TaskStatus.FAILED
    assert task_res.summary_card["engineering_status"] == "DELIVERY_BLOCKED"
    assert task_res.summary_card["delivery_card"] is None
    assert task_res.report_markdown is None, "Stale markdown report must not leak when delivery is blocked"
    assert task_res.report_html is None, "Blocked official delivery must not emit a report, including a diagnostic draft"
    assert len(task_res.errors) >= 1
    assert any("DELIVERY_BLOCKED" in str(e) or "delivery blocked" in str(e).lower() for e in task_res.errors)


def test_unadmitted_foreign_figures_strictly_blocked_in_official_pipeline(tmp_path: Path):
    """P0-2 Anti-Tamper: Unknown or unadmitted figures passed to official pipeline are strictly blocked."""
    pipeline = DeterministicReportPipeline(
        builder=AdaptiveReportBuilder(physics_domain="structural", objective=AnalysisObjective.STATIC_STRENGTH)
    )

    mock_odb = tmp_path / "test.odb"
    mock_odb.write_bytes(b"\x7fSIMULIA_ODB_BINARY_HEADER" + b"\x00" * 1024)
    odb_sha = hashlib.sha256(mock_odb.read_bytes()).hexdigest()

    run_id = "RUN-SEC-TEST"
    input_hash = "INP-SEC-TEST"

    spec = VisualizationSpec(
        artifact_id="FIG-S-001",
        visualization_type="stress_hotspot",
        field_name="S",
        component="mises",
        target_filename="mises.svg",
    )
    auth_fig = _create_mock_authentic_figure(
        tmp_path, "mises.svg", spec, run_id, input_hash, odb_sha
    )

    # An unauthorized / foreign figure not admitted against any spec
    forged_file = tmp_path / "unauthorized_plot.png"
    forged_file.write_bytes(b"\x89PNG\r\n\x1a\n" + b"\x00" * 100)
    forged_fig = ReportFigure(
        kind="arbitrary_plot",
        path=str(forged_file.as_posix()),
        caption="Forged External Plot",
        source="unknown_external_attacker",
        metadata={"run_id": run_id},
    )

    acceptance = {"status": "PASS", "deliverable": True}

    with pytest.raises(PermissionError) as exc_info:
        pipeline.build_and_render(
            output_dir=tmp_path,
            title="Structural Strength Verification",
            case_id="case_security",
            run_id=run_id,
            input_hash=input_hash,
            odb_path=mock_odb,
            model_info={"name": "Beam", "max_mises_mpa": 250.0},
            results_info=(),
            acceptance_info=acceptance,
            visualization_specs=[spec],
            figures=[auth_fig, forged_fig],  # Contains forged foreign figure!
            require_deliverable=True,
        )

    assert "unadmitted / unrequested figure" in str(exc_info.value).lower()


def test_corrupt_png_image_integrity_fail_closed(tmp_path: Path):
    """P0-2 Physical Integrity: Non-PNG or truncated PNG files must be blocked fail-closed."""
    run_id = "RUN-CORRUPT-PNG"
    input_hash = "INP-CORRUPT-PNG"
    odb_sha = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"

    # Create a corrupted file with fake PNG suffix but garbage bytes
    corrupt_file = tmp_path / "corrupt.png"
    corrupt_bytes = b"NOT_A_VALID_PNG_HEADER_JUST_GARBAGE"
    corrupt_file.write_bytes(corrupt_bytes)

    # 1. Direct unit assertion on verify_png_image_integrity
    with pytest.raises(ValueError) as val_err:
        verify_png_image_integrity(corrupt_file)
    assert "invalid png magic signature" in str(val_err.value).lower()

    # 2. Admission gate assertion: admit_figure_for_reuse must refuse corrupted PNG
    corrupt_sha = hashlib.sha256(corrupt_bytes).hexdigest()
    fig = ReportFigure(
        kind="stress_hotspot",
        path=str(corrupt_file.as_posix()),
        caption="Corrupted image",
        source="test",
        metadata={
            "run_id": run_id,
            "input_hash": input_hash,
            "odb_sha256": odb_sha,
            "image_sha256": corrupt_sha,
            "field": "S",
            "component": "mises",
        },
    )

    is_admitted, reason = admit_figure_for_reuse(
        figure=fig,
        current_run_id=run_id,
        current_input_hash=input_hash,
        current_odb_hash=odb_sha,
        target_field="S",
        target_component="mises",
    )
    assert is_admitted is False
    assert "corrupt or not a valid png" in reason.lower()


